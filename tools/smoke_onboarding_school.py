"""Граница нативного поиска и вебвью questions."""
def check_feature(browser, port, errors, check):
    page = browser.new_page(viewport={"width": 390, "height": 844})
    page.set_default_timeout(6000)
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.on("console", lambda message: errors.append(message.text) if message.type == "error" else None)
    url = f"http://127.0.0.1:{port}/features/onboarding-school/"
    page.goto(url)
    rows = page.locator(".row")
    search = page.locator("#query")
    frame = page.frame_locator("iframe")
    for width in (375, 390, 430):
        page.set_viewport_size({"width": width, "height": 740})
        check(f"поиск и пропуск помещаются при ширине {width}", page.locator("#skip").bounding_box()["y"] < 740
              and page.evaluate("document.documentElement.scrollWidth === innerWidth"))
    search.fill("неизвестное место")
    check("пустая выдача", page.locator("#empty").is_visible() and rows.count() == 0)
    page.locator("#clear").click()
    for kind, number in (("школа", 23), ("колледж", 1), ("универ", 4)):
        page.get_by_role("button", name=kind, exact=True).click()
        check("фильтр " + kind, rows.count() == number)
        if kind == "школа":
            rows.last.scroll_into_view_if_needed()
            check("длинный список школ прокручивается до последней строки",
                  page.locator("#results").evaluate("e => e.scrollTop > e.clientHeight && e.scrollHeight - e.clientHeight - e.scrollTop <= 10"))
    search.fill("МЕДИЦИН")
    rows.first.click()
    frame.get_by_role("heading", name="ивановский государственный медицинский университет").wait_for()
    check("гостевые действия универа", frame.get_by_role("button", name="вступить в универ", exact=True).is_visible())
    preview = frame.locator(".school-chat-message").inner_text()
    frame.get_by_role("button", name="сообщения из чатика", exact=False).click()
    frame.get_by_text(preview, exact=True).last.wait_for()
    page.locator("#web-back").click()
    frame.get_by_role("button", name="вступить в универ", exact=True).wait_for()
    check("из превью чата стрелка возвращает к вступлению", frame.get_by_role("button", name="я учусь в другом универе").is_visible())
    frame.get_by_role("button", name="вопросы", exact=False).first.click()
    check("у гостя открыты опубликованные вопросы", frame.locator("article").count() > 0
          and frame.get_by_text("задать вопрос", exact=True).count() == 0)
    frame.get_by_role("button", name="я учусь в другом универе").click()
    page.locator("#search").wait_for()
    check("закрытие до вступления возвращает выдачу", search.input_value() == "МЕДИЦИН"
          and page.locator('.filters [aria-pressed=true]').inner_text() == "универ" and rows.count() == 1)
    page.locator("#clear").click()
    page.locator('.filters [aria-pressed=true]').click()
    page.locator("#results").evaluate("e => e.scrollTop = e.scrollHeight")
    offset = page.locator("#results").evaluate("e => e.scrollTop")
    rows.last.click()
    frame.get_by_role("button", name="вступить в школу", exact=True).wait_for()
    page.go_back()
    page.locator("#search").wait_for()
    check("системная стрелка сохраняет прокрутку", offset > 0 and page.locator("#results").evaluate("e => e.scrollTop") == offset)
    for exit_method in ("продолжить", "крестик", "стрелка"):
        rows.first.click()
        frame.get_by_role("button", name="вступить в школу", exact=True).click()
        frame.get_by_role("button", name="продолжить").wait_for()
        if exit_method == "продолжить":
            proceed = frame.get_by_role("button", name=exit_method)
            color = lambda: proceed.evaluate("e => getComputedStyle(e).backgroundColor")
            check("до заявки выход вторичный", color() == "rgb(36, 36, 36)")
            start = proceed.bounding_box()
            frame.get_by_role("button", name="добавить", exact=True).nth(12).click()
            check("белая кнопка остаётся внизу после прокрутки и заявки",
                  color() == "rgb(255, 255, 255)" and proceed.bounding_box() == start)
            frame.get_by_role("button", name="добавить", exact=True).first.click()
            page.reload()
            proceed.wait_for()
            cancel = frame.get_by_role("button", name="отменить", exact=True)
            check("после перезагрузки обе заявки сохранены", cancel.count() == 2)
            cancel.first.click()
            check("если осталась заявка, выход основной", color() == "rgb(255, 255, 255)")
            cancel.first.click()
            check("отмена последней заявки возвращает вторичный выход", color() == "rgb(36, 36, 36)")
            frame.get_by_role("button", name="добавить", exact=True).first.click()
            frame.get_by_role("button", name="вопросы", exact=False).first.click()
            frame.get_by_role("button", name="задать вопрос").click()
            frame.get_by_placeholder("введи имя").fill("маш")
            frame.get_by_role("button", name="маша", exact=False).first.click()
            frame.get_by_placeholder("твой вопрос").fill("где встречаемся?")
            frame.get_by_role("button", name="спросить анонимно").click()
            check("отправка вопроса из исходного questions", frame.get_by_text("где встречаемся?", exact=False).count() == 1)
            frame.get_by_role("button", name="задать вопрос").click()
            page.locator("#web-back").click()
            frame.get_by_role("button", name="спросить анонимно").wait_for(state="hidden")
            check("стрелка закрывает вложенную шторку", frame.get_by_role("button", name="спросить анонимно").count() == 0)
            frame.get_by_role("button", name=exit_method).click()
        elif exit_method == "крестик":
            frame.get_by_role("button", name="посмотри, о чём говорят ученики").click()
            page.locator("#web-close").click()
        else:
            page.locator("#web-back").click()
        page.locator("#end").wait_for()
        check("после вступления — следующий шаг: " + exit_method, page.locator("#end-title").inner_text() == "учебное заведение добавлено")
        page.locator("#replay").click()
    page.set_viewport_size({"width": 375, "height": 410})
    search.fill("неизвестно")
    page.locator("#skip").click()
    check("пропуск при коротком окне и пустом поиске", page.locator("#end-title").inner_text() == "шаг пропущен")
    page.close()
