def main():
    server,port=serve();errors=[];checks=[]
    def check(name,ok):
        checks.append((name,ok));print(('ok ' if ok else 'FAIL ')+name,flush=True)
    try:
        with sync_playwright() as p:
            b=p.chromium.launch();check_feature(b,port,errors,check);b.close()
        check('no script or resource errors',not errors)
        for e in errors:print('console:',e,flush=True)
        print(f'{sum(ok for _,ok in checks)}/{len(checks)} checks passed',flush=True)
        return int(any(not ok for _,ok in checks))
    finally:server.shutdown()
if __name__=='__main__':raise SystemExit(main())
